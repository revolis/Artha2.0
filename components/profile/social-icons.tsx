function findBrand(platform: string): Brand | undefined {
  return BRANDS.find((brand) => brand.match.test(platform.trim()))
}

/** The tidy display name for a platform — the brand's own spelling if known. */
export function socialLabel(platform: string): string {
  return findBrand(platform)?.label ?? platform.trim() ?? "Link"
}

/**
 * The real logo for a platform, falling back to a neutral icon for anything
 * that isn't a recognised network.
 */
export function SocialIcon({
  platform,
  className,
}: {
  platform: string
  className?: string
}) {
  const brand = findBrand(platform)

  if (brand) {
    return (
      <svg
        viewBox="0 0 24 24"
        fill="currentColor"
        aria-hidden
        className={className}
      >
        <path d={brand.path} />
      </svg>
    )
  }

  // createElement rather than a capitalised local so the linter doesn't read
  // this as defining a component during render.
  const fallback = /mail|email|@/i.test(platform)
    ? Mail
    : /site|web|blog|portfolio|home/i.test(platform)
      ? Globe
      : Link2
  return React.createElement(fallback, { className, "aria-hidden": true })
}
